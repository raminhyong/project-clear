/**
 * Find the room record for a 5-digit student code.
 * @param {string|number} code
 * @returns {{room:string, slug:string, title:string, name:string}|null}
 */
window.findRoomByStudentCode = function (code) {
  const key = String(code == null ? '' : code).trim();
  if (!/^\d{5}$/.test(key)) return null;
  return window.STUDENT_ROOM_MAP[key] || null;
};
